import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { checkData } from './check-data.mjs';
import { levelRevision, solutionCells } from '../src/analytics-protocol.js';

const { levels } = await checkData();
const workerRoot = new URL('../worker/', import.meta.url);
await mkdir(workerRoot, { recursive: true });
const supportedLevels = await Promise.all(levels.map(async (level) => ({ id: level.id, revision: await levelRevision(level), entryCount: level.entries.length, solution: solutionCells(level) })));
const declaration = `// Generated by npm run build:worker. Commit this file after changing puzzles.\nexport const supportedLevels = ${JSON.stringify(supportedLevels)};\n`;
await writeFile(new URL('levels.generated.js', workerRoot), declaration);
const source = await readFile(new URL('index.js', workerRoot), 'utf8');
const bundled = source.replace("import { supportedLevels } from './levels.generated.js';", declaration.replace('export const', 'const'));
await mkdir(new URL('dashboard/', workerRoot), { recursive: true });
await writeFile(new URL('dashboard/worker.js', workerRoot), bundled);
console.log(`统计 Worker 已生成，支持 ${supportedLevels.length} 个关卡。`);
